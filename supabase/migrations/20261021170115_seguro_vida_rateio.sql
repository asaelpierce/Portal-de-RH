  public.seguro_vida_obter(integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.seguro_vida_conferir(integer,text,text,jsonb), public.seguro_vida_historico(integer),
  public.seguro_vida_obter(integer,text) TO authenticated;
