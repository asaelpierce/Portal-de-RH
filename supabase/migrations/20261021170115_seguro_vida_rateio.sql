-- Seguro de vida (Prudential VG) — rateio mensal por centro de custo (21/10/2026).
-- O RH anexa o demonstrativo (PDF) no portal; o navegador lê as linhas e esta função cruza com o cadastro (CPF, ou nome
-- se não achar o CPF), usa o centro de custo da folha (usuarios.centro_custo, fonte oficial), soma por centro de custo,
-- monta a conferência e guarda o relatório do mês. Só RH. Tabela fechada ao navegador.

CREATE TABLE public.seguro_vida_relatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia text NOT NULL UNIQUE CHECK (competencia ~ '^\d{4}-\d{2}$'),
  arquivo_nome text,
  total numeric(12,2) NOT NULL,
  pessoas integer NOT NULL,
  linhas jsonb NOT NULL,
  rateio jsonb NOT NULL,
  conferencia jsonb NOT NULL,
  gerado_por integer REFERENCES public.usuarios(id),
  gerado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.seguro_vida_relatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.seguro_vida_relatorios FROM anon, authenticated;

-- Nome comparável: sem acento, maiúsculas, espaços simples.
CREATE OR REPLACE FUNCTION public.sv_norm(p text) RETURNS text LANGUAGE sql IMMUTABLE SET search_path TO 'public' AS $$
  SELECT regexp_replace(upper(translate(coalesce(p,''), 'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ', 'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC')), '\s+', ' ', 'g');
$$;

CREATE OR REPLACE FUNCTION public.seguro_vida_conferir(p_pedido_por integer, p_competencia text, p_arquivo text, p_linhas jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_linhas jsonb; v_rateio jsonb; v_conf jsonb; v_total numeric; v_pessoas int; v_padrao numeric;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio do seguro de vida.'; END IF;
  IF coalesce(p_competencia,'') !~ '^\d{4}-\d{2}$' THEN RAISE EXCEPTION 'Competência inválida (esperado AAAA-MM).'; END IF;
  IF jsonb_typeof(p_linhas) <> 'array' OR jsonb_array_length(p_linhas) = 0 THEN RAISE EXCEPTION 'Nenhum segurado lido do demonstrativo.'; END IF;

  -- Cada linha do demonstrativo + o cadastro correspondente (CPF; se não houver, nome).
  WITH l AS (
    SELECT x.ord, x.e->>'nome' AS nome, regexp_replace(coalesce(x.e->>'cpf',''),'\D','','g') AS cpf,
           coalesce(x.e->>'movimentacao','') AS mov, (x.e->>'premio')::numeric AS premio, (x.e->>'capital')::numeric AS capital,
           x.e->>'nascimento' AS nascimento, x.e->>'inicio' AS inicio
    FROM jsonb_array_elements(p_linhas) WITH ORDINALITY AS x(e, ord)
  ), m AS (
    SELECT l.*, coalesce(pc.id, pn.id) AS uid, CASE WHEN pc.id IS NOT NULL THEN 'cpf' WHEN pn.id IS NOT NULL THEN 'nome' END AS achado_por
    FROM l
    LEFT JOIN LATERAL (SELECT u.id FROM usuarios u JOIN colaboradores_documentos d ON d.usuario_id = u.id
                       WHERE regexp_replace(coalesce(d.cpf,''),'\D','','g') = l.cpf AND l.cpf <> '' ORDER BY (u.status='ativo') DESC LIMIT 1) pc ON true
    LEFT JOIN LATERAL (SELECT u.id FROM usuarios u WHERE pc.id IS NULL AND sv_norm(u.name) = sv_norm(l.nome) ORDER BY (u.status='ativo') DESC LIMIT 1) pn ON true
  )
  SELECT jsonb_agg(jsonb_build_object('nome', m.nome, 'cpf', m.cpf, 'movimentacao', m.mov, 'premio', m.premio, 'capital', m.capital,
           'nascimento', m.nascimento, 'inicio', m.inicio, 'usuario_id', u.id, 'achado_por', m.achado_por,
           'centro_custo', u.centro_custo, 'cargo', u.cargo, 'admissao', u.admissao, 'status', u.status,
           'data_desligamento', u.data_desligamento) ORDER BY m.ord)
  INTO v_linhas FROM m LEFT JOIN usuarios u ON u.id = m.uid;

  SELECT round(sum((e->>'premio')::numeric),2), count(*) FILTER (WHERE (e->>'premio')::numeric > 0)
  INTO v_total, v_pessoas FROM jsonb_array_elements(v_linhas) e;
  -- Prêmio padrão = o valor mais comum entre os cobrados (hoje 4,47).
  SELECT (e->>'premio')::numeric INTO v_padrao FROM jsonb_array_elements(v_linhas) e WHERE (e->>'premio')::numeric > 0
  GROUP BY 1 ORDER BY count(*) DESC, 1 LIMIT 1;

  SELECT coalesce(jsonb_agg(jsonb_build_object('centro_custo', cc, 'pessoas', n, 'valor', v) ORDER BY cc), '[]'::jsonb)
  INTO v_rateio FROM (
    SELECT coalesce(e->>'centro_custo', 'SEM CENTRO DE CUSTO (verificar)') AS cc, count(*) AS n, round(sum((e->>'premio')::numeric),2) AS v
    FROM jsonb_array_elements(v_linhas) e WHERE (e->>'premio')::numeric > 0 GROUP BY 1) r;

  v_conf := jsonb_build_object(
    'premio_padrao', v_padrao,
    'nao_encontrados', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e WHERE e->>'usuario_id' IS NULL), '[]'),
    'achados_pelo_nome', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e WHERE e->>'achado_por' = 'nome'), '[]'),
    'sem_centro_custo', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e
                                  WHERE e->>'usuario_id' IS NOT NULL AND e->>'centro_custo' IS NULL AND (e->>'premio')::numeric > 0), '[]'),
    'desligados_cobrados', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', e->>'nome', 'desligamento', e->>'data_desligamento'))
                                  FROM jsonb_array_elements(v_linhas) e WHERE e->>'status' = 'desligado' AND (e->>'premio')::numeric > 0), '[]'),
    'exclusoes', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e WHERE e->>'movimentacao' ILIKE 'exclus%'), '[]'),
    'inclusoes', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e WHERE e->>'movimentacao' ILIKE 'inclus%'), '[]'),
    'premio_diferente', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', e->>'nome', 'premio', (e->>'premio')::numeric, 'capital', (e->>'capital')::numeric))
                                  FROM jsonb_array_elements(v_linhas) e WHERE (e->>'premio')::numeric > 0 AND (e->>'premio')::numeric <> v_padrao), '[]'),
    'ativos_fora_do_seguro', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', u.name, 'cargo', u.cargo, 'admissao', u.admissao,
                                  'aprendiz', u.cargo ILIKE '%aprendiz%') ORDER BY u.name)
                                  FROM usuarios u WHERE u.status = 'ativo' AND u.cadastro IS NOT NULL
                                    AND u.id NOT IN (SELECT (e->>'usuario_id')::int FROM jsonb_array_elements(v_linhas) e
                                                     WHERE e->>'usuario_id' IS NOT NULL AND (e->>'premio')::numeric > 0)), '[]'));

  INSERT INTO seguro_vida_relatorios (competencia, arquivo_nome, total, pessoas, linhas, rateio, conferencia, gerado_por)
  VALUES (p_competencia, left(p_arquivo, 200), v_total, v_pessoas, v_linhas, v_rateio, v_conf, p_pedido_por)
  ON CONFLICT (competencia) DO UPDATE SET arquivo_nome = EXCLUDED.arquivo_nome, total = EXCLUDED.total, pessoas = EXCLUDED.pessoas,
    linhas = EXCLUDED.linhas, rateio = EXCLUDED.rateio, conferencia = EXCLUDED.conferencia, gerado_por = EXCLUDED.gerado_por, gerado_em = now();

  RETURN jsonb_build_object('competencia', p_competencia, 'arquivo_nome', p_arquivo, 'total', v_total, 'pessoas', v_pessoas,
                            'linhas', v_linhas, 'rateio', v_rateio, 'conferencia', v_conf, 'gerado_em', now());
END; $$;

CREATE OR REPLACE FUNCTION public.seguro_vida_historico(p_pedido_por integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do seguro de vida.'; END IF;
  RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('competencia', r.competencia, 'total', r.total, 'pessoas', r.pessoas,
            'arquivo_nome', r.arquivo_nome, 'gerado_em', r.gerado_em, 'gerado_por', u.name) ORDER BY r.competencia DESC)
          FROM seguro_vida_relatorios r LEFT JOIN usuarios u ON u.id = r.gerado_por), '[]'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.seguro_vida_obter(p_pedido_por integer, p_competencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
DECLARE r seguro_vida_relatorios;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do seguro de vida.'; END IF;
  SELECT * INTO r FROM seguro_vida_relatorios WHERE competencia = p_competencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Relatório de % não encontrado.', p_competencia; END IF;
  RETURN jsonb_build_object('competencia', r.competencia, 'arquivo_nome', r.arquivo_nome, 'total', r.total, 'pessoas', r.pessoas,
                            'linhas', r.linhas, 'rateio', r.rateio, 'conferencia', r.conferencia, 'gerado_em', r.gerado_em);
END; $$;

REVOKE ALL ON FUNCTION public.sv_norm(text) FROM PUBLIC, anon, authenticated;
