CREATE TABLE public.login_falhas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  motivo text,
  criado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.login_falhas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.login_falhas FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.registrar_falha_login(p_email text, p_motivo text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
BEGIN
  IF (SELECT count(*) FROM login_falhas WHERE criado_em > now() - interval '1 hour') >= 300 THEN RETURN; END IF;  -- contra abuso
  INSERT INTO login_falhas (email, motivo) VALUES (left(lower(btrim(coalesce(p_email,''))),120), left(coalesce(p_motivo,''),200));
END; $$;
REVOKE ALL ON FUNCTION public.registrar_falha_login(text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.registrar_falha_login(text,text) TO anon, authenticated;

-- 2) Pessoas cadastradas no futuro (ou que ganharem e-mail/senha depois) recebem conta no login novo automaticamente;
--    senha nova no cadastro vira a senha do login novo. Mesma forma da etapa 1 (hash bcrypt copiado, nada é lido).
CREATE OR REPLACE FUNCTION public.garante_conta_login() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'auth' AS $$
DECLARE v_aid uuid;
BEGIN
  IF NEW.auth_id IS NOT NULL THEN
    IF NEW.password_hash IS DISTINCT FROM OLD.password_hash AND NEW.password_hash LIKE '$2a$%' THEN
      UPDATE auth.users SET encrypted_password = NEW.password_hash, updated_at = now() WHERE id = NEW.auth_id;
    END IF;
    RETURN NEW;
  END IF;
  IF coalesce(NEW.status,'ativo') <> 'ativo' OR NEW.email IS NULL OR btrim(NEW.email) = '' OR coalesce(NEW.password_hash,'') NOT LIKE '$2a$%' THEN
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM auth.users WHERE email = lower(btrim(NEW.email))) THEN RETURN NEW; END IF;  -- não duplica
  v_aid := gen_random_uuid();
  INSERT INTO auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data,
    created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current,
    phone_change, phone_change_token, reauthentication_token, is_sso_user, is_anonymous)
  VALUES ('00000000-0000-0000-0000-000000000000', v_aid, 'authenticated', 'authenticated', lower(btrim(NEW.email)), NEW.password_hash, now(),
    '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('usuario_id', NEW.id), now(), now(), '', '', '', '', '', '', '', '', false, false);
  INSERT INTO auth.identities (provider_id, user_id, identity_data, provider, created_at, updated_at)
  VALUES (v_aid::text, v_aid, jsonb_build_object('sub', v_aid::text, 'email', lower(btrim(NEW.email)), 'email_verified', true, 'phone_verified', false), 'email', now(), now());
  NEW.auth_id := v_aid;
  RETURN NEW;
END; $$;
REVOKE ALL ON FUNCTION public.garante_conta_login() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER usuarios_garante_conta_login BEFORE INSERT OR UPDATE OF email, password_hash, status ON public.usuarios
  FOR EACH ROW EXECUTE FUNCTION public.garante_conta_login();

-- 3) Funções que as regras das tabelas usam (quem sou eu, meu nível, é da minha equipe).
CREATE OR REPLACE FUNCTION public.eu() RETURNS integer LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT id FROM usuarios WHERE auth_id = auth.uid() AND auth.uid() IS NOT NULL AND coalesce(status,'ativo') = 'ativo';
$$;
CREATE OR REPLACE FUNCTION public.eu_nivel() RETURNS integer LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT coalesce((SELECT nivel_perfil(role) FROM usuarios WHERE auth_id = auth.uid() AND auth.uid() IS NOT NULL AND coalesce(status,'ativo') = 'ativo'), 0);
$$;
CREATE OR REPLACE FUNCTION public.da_minha_equipe(p_usuario integer) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT EXISTS (SELECT 1 FROM usuarios u WHERE u.id = p_usuario AND public.eu() IN (u.lider_id, u.gestor_id));
$$;
CREATE OR REPLACE FUNCTION public.cadastro_visivel(p_cadastro text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT public.eu_nivel() >= 4 OR EXISTS (SELECT 1 FROM usuarios u WHERE u.cadastro = p_cadastro AND public.eu() IN (u.id, u.lider_id, u.gestor_id));
$$;
REVOKE ALL ON FUNCTION public.eu(), public.eu_nivel(), public.da_minha_equipe(integer), public.cadastro_visivel(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.eu(), public.eu_nivel(), public.da_minha_equipe(integer), public.cadastro_visivel(text) TO authenticated;
