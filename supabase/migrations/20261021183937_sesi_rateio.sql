-- Aplicada em 21/10/2026 (versão 20261021183937). Verificado (rollback, sessão do RH) com a relação real de 16/09/2026:
-- 4 de 4 titulares encontrados pelo CPF; total R$ 190,00 = total impresso; rateio pelo centro de custo da folha.
--
-- Clube SESI Vespasiano — rateio mensal por centro de custo (21/10/2026).
-- O RH anexa a "Relação de Conveniados" (PDF) do SESI. O valor de cada titular é o valor integral (confirmado pelo
-- Asael). Cada linha é ligada ao cadastro pelo CPF (colaboradores_documentos; se não houver, pelo nome) e rateada pelo
-- centro de custo da folha da BRIT. Competência = mês da data de corte do relatório.

CREATE TABLE public.sesi_relatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia text NOT NULL UNIQUE CHECK (competencia ~ '^\d{4}-\d{2}$'),
  data_corte date, contrato text, vigencia text, arquivo_nome text,
  total numeric(12,2) NOT NULL, pessoas integer NOT NULL,
  linhas jsonb NOT NULL, rateio jsonb NOT NULL, conferencia jsonb NOT NULL,
  gerado_por integer REFERENCES public.usuarios(id), gerado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.sesi_relatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sesi_relatorios FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.sesi_conferir(p_pedido_por integer, p_competencia text, p_cabecalho jsonb, p_arquivo text, p_linhas jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_linhas jsonb; v_rateio jsonb; v_conf jsonb; v_total numeric; v_pessoas int; c jsonb := coalesce(p_cabecalho,'{}'::jsonb);
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio do Clube SESI.'; END IF;
  IF coalesce(p_competencia,'') !~ '^\d{4}-\d{2}$' THEN RAISE EXCEPTION 'Competência inválida (esperado AAAA-MM).'; END IF;
  IF jsonb_typeof(p_linhas) <> 'array' OR jsonb_array_length(p_linhas) = 0 THEN RAISE EXCEPTION 'Nenhum conveniado lido da relação.'; END IF;

  SELECT jsonb_agg(jsonb_build_object('cpf', l.cpf, 'nome', l.nome, 'categoria', l.categoria, 'valor', l.valor,
           'usuario_id', u.id, 'colaborador', u.name, 'status', u.status, 'data_desligamento', u.data_desligamento,
           'centro_custo', u.centro_custo, 'achado_por', CASE WHEN pc.id IS NOT NULL THEN 'cpf' WHEN pn.id IS NOT NULL THEN 'nome' END) ORDER BY l.ord)
  INTO v_linhas
  FROM (SELECT x.ord, regexp_replace(coalesce(x.e->>'cpf',''),'\D','','g') AS cpf, x.e->>'nome' AS nome, x.e->>'categoria' AS categoria,
               (x.e->>'valor')::numeric AS valor FROM jsonb_array_elements(p_linhas) WITH ORDINALITY AS x(e, ord)) l
  LEFT JOIN LATERAL (SELECT u2.id FROM usuarios u2 JOIN colaboradores_documentos d ON d.usuario_id = u2.id
                     WHERE l.cpf <> '' AND lpad(regexp_replace(coalesce(d.cpf,''),'\D','','g'),11,'0') = lpad(l.cpf,11,'0')
                     ORDER BY (u2.status = 'ativo') DESC LIMIT 1) pc ON true
  LEFT JOIN LATERAL (SELECT u3.id FROM usuarios u3 WHERE pc.id IS NULL AND sv_norm(u3.name) = sv_norm(l.nome)
                     ORDER BY (u3.status = 'ativo') DESC LIMIT 1) pn ON true
  LEFT JOIN usuarios u ON u.id = coalesce(pc.id, pn.id);

  SELECT round(sum((e->>'valor')::numeric),2), count(*) INTO v_total, v_pessoas FROM jsonb_array_elements(v_linhas) e;
  SELECT coalesce(jsonb_agg(jsonb_build_object('centro_custo', cc, 'pessoas', n, 'valor', v) ORDER BY cc), '[]'::jsonb) INTO v_rateio FROM (
    SELECT coalesce(e->>'centro_custo', 'SEM CENTRO DE CUSTO (verificar)') AS cc, count(*) AS n, round(sum((e->>'valor')::numeric),2) AS v
    FROM jsonb_array_elements(v_linhas) e GROUP BY 1) r;

  v_conf := jsonb_build_object(
    'nao_encontrados', coalesce((SELECT jsonb_agg(e->>'nome') FROM jsonb_array_elements(v_linhas) e WHERE e->>'usuario_id' IS NULL), '[]'),
    'achados_pelo_nome', coalesce((SELECT jsonb_agg(e->>'colaborador') FROM jsonb_array_elements(v_linhas) e WHERE e->>'achado_por' = 'nome'), '[]'),
    'sem_centro_custo', coalesce((SELECT jsonb_agg(e->>'colaborador') FROM jsonb_array_elements(v_linhas) e WHERE e->>'usuario_id' IS NOT NULL AND e->>'centro_custo' IS NULL), '[]'),
    'desligados_conveniados', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', e->>'colaborador', 'desligamento', e->>'data_desligamento', 'valor', (e->>'valor')::numeric))
                                 FROM jsonb_array_elements(v_linhas) e WHERE e->>'status' = 'desligado'), '[]'));

  INSERT INTO sesi_relatorios (competencia, data_corte, contrato, vigencia, arquivo_nome, total, pessoas, linhas, rateio, conferencia, gerado_por)
  VALUES (p_competencia, nullif(c->>'data_corte','')::date, left(c->>'contrato',30), left(c->>'vigencia',60), left(p_arquivo,200),
          v_total, v_pessoas, v_linhas, v_rateio, v_conf, p_pedido_por)
  ON CONFLICT (competencia) DO UPDATE SET data_corte = EXCLUDED.data_corte, contrato = EXCLUDED.contrato, vigencia = EXCLUDED.vigencia,
    arquivo_nome = EXCLUDED.arquivo_nome, total = EXCLUDED.total, pessoas = EXCLUDED.pessoas, linhas = EXCLUDED.linhas,
    rateio = EXCLUDED.rateio, conferencia = EXCLUDED.conferencia, gerado_por = EXCLUDED.gerado_por, gerado_em = now();

  RETURN jsonb_build_object('competencia', p_competencia, 'data_corte', c->>'data_corte', 'contrato', c->>'contrato', 'vigencia', c->>'vigencia',
    'arquivo_nome', p_arquivo, 'total', v_total, 'pessoas', v_pessoas, 'linhas', v_linhas, 'rateio', v_rateio, 'conferencia', v_conf, 'gerado_em', now());
END; $$;

CREATE OR REPLACE FUNCTION public.sesi_historico(p_pedido_por integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do Clube SESI.'; END IF;
  RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('competencia', r.competencia, 'data_corte', r.data_corte, 'total', r.total, 'pessoas', r.pessoas,
            'gerado_em', r.gerado_em, 'gerado_por', u.name) ORDER BY r.competencia DESC)
          FROM sesi_relatorios r LEFT JOIN usuarios u ON u.id = r.gerado_por), '[]'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.sesi_obter(p_pedido_por integer, p_competencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
DECLARE r sesi_relatorios;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do Clube SESI.'; END IF;
  SELECT * INTO r FROM sesi_relatorios WHERE competencia = p_competencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Relatório de % não encontrado.', p_competencia; END IF;
  RETURN jsonb_build_object('competencia', r.competencia, 'data_corte', r.data_corte, 'contrato', r.contrato, 'vigencia', r.vigencia,
    'arquivo_nome', r.arquivo_nome, 'total', r.total, 'pessoas', r.pessoas, 'linhas', r.linhas, 'rateio', r.rateio, 'conferencia', r.conferencia, 'gerado_em', r.gerado_em);
END; $$;

REVOKE ALL ON FUNCTION public.sesi_conferir(integer,text,jsonb,text,jsonb), public.sesi_historico(integer), public.sesi_obter(integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sesi_conferir(integer,text,jsonb,text,jsonb), public.sesi_historico(integer), public.sesi_obter(integer,text) TO authenticated;
