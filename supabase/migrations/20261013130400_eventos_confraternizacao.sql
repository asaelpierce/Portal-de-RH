CREATE TABLE public.eventos (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       text NOT NULL,
  slug       text NOT NULL UNIQUE,                 -- vai no link: ?evento=<slug>
  aberto     boolean NOT NULL DEFAULT true,
  prazo      date,                                 -- último dia para responder (opcional)
  criado_por integer REFERENCES public.usuarios(id),
  criado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.evento_respostas (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id      bigint NOT NULL REFERENCES public.eventos(id) ON DELETE CASCADE,
  usuario_id     integer NOT NULL REFERENCES public.usuarios(id),
  vai_participar boolean NOT NULL,
  email          text,                             -- opcional, para o RH mandar recados
  ja_participou  boolean,                          -- "Você já participou de um evento da Kalenborn?"
  acompanhantes  jsonb NOT NULL DEFAULT '[]',      -- [{nome, idade, parentesco}]
  qtd_adultos    integer NOT NULL DEFAULT 0,       -- acima de 18 (idade >= 18)
  qtd_13_17      integer NOT NULL DEFAULT 0,
  qtd_ate_12     integer NOT NULL DEFAULT 0,
  tempo_empresa  text,                             -- calculado pela admissão no momento da resposta
  respondido_em  timestamptz NOT NULL DEFAULT now(),
  atualizado_em  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (evento_id, usuario_id)
);

