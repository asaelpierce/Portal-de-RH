-- Tempo de empresa por extenso a partir da admissão (ex.: "3 anos e 2 meses").
CREATE OR REPLACE FUNCTION public.tempo_de_empresa(p_admissao date, p_ref date)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE
    WHEN p_admissao IS NULL THEN NULL
    WHEN a.anos = 0 AND a.meses = 0 THEN 'menos de 1 mês'
    ELSE concat_ws(' e ',
      CASE WHEN a.anos > 0 THEN a.anos || CASE WHEN a.anos = 1 THEN ' ano' ELSE ' anos' END END,
      CASE WHEN a.meses > 0 THEN a.meses || CASE WHEN a.meses = 1 THEN ' mês' ELSE ' meses' END END)
  END
  FROM (SELECT extract(year from age(p_ref, p_admissao))::int AS anos, extract(month from age(p_ref, p_admissao))::int AS meses) a;
$$;

-- Resposta pelo link público (sem login). Valida tudo no servidor; uma resposta por pessoa por evento (reenviar atualiza).
CREATE OR REPLACE FUNCTION public.responder_evento(p_slug text, p_usuario_id integer, p_vai boolean, p_email text,
  p_ja_participou boolean, p_acompanhantes jsonb)
RETURNS TABLE(respondido_em timestamptz, atualizado_em timestamptz, primeira_vez boolean)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE v_ev eventos; v_u usuarios; v_hoje date := (now() AT TIME ZONE 'America/Sao_Paulo')::date;
        v_ac jsonb := coalesce(p_acompanhantes, '[]'::jsonb); v_item jsonb; v_idade int; v_ad int := 0; v_ad13 int := 0; v_cr int := 0;
        v_email text := nullif(btrim(coalesce(p_email,'')), ''); v_existia boolean;
BEGIN
  SELECT * INTO v_ev FROM eventos WHERE slug = p_slug;
  IF NOT FOUND THEN RAISE EXCEPTION 'Evento não encontrado.'; END IF;
  IF NOT v_ev.aberto OR (v_ev.prazo IS NOT NULL AND v_hoje > v_ev.prazo) THEN RAISE EXCEPTION 'As inscrições deste evento estão encerradas.'; END IF;
  SELECT * INTO v_u FROM usuarios WHERE id = p_usuario_id AND coalesce(status,'ativo') = 'ativo' AND cadastro IS NOT NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'Colaborador não encontrado na lista de ativos.'; END IF;
  IF p_vai IS NULL THEN RAISE EXCEPTION 'Informe se vai participar.'; END IF;
  IF jsonb_typeof(v_ac) <> 'array' THEN RAISE EXCEPTION 'Lista de acompanhantes inválida.'; END IF;
  IF NOT p_vai THEN v_ac := '[]'::jsonb; END IF;            -- quem não vai não leva acompanhantes
  IF jsonb_array_length(v_ac) > 15 THEN RAISE EXCEPTION 'Máximo de 15 acompanhantes.'; END IF;
  IF v_email IS NOT NULL AND v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN RAISE EXCEPTION 'E-mail inválido.'; END IF;
  FOR v_item IN SELECT * FROM jsonb_array_elements(v_ac) LOOP
    IF length(btrim(coalesce(v_item->>'nome',''))) < 3 THEN RAISE EXCEPTION 'Informe o nome completo de cada acompanhante.'; END IF;
    IF coalesce(v_item->>'idade','') !~ '^\d{1,3}$' THEN RAISE EXCEPTION 'Idade inválida para %.', v_item->>'nome'; END IF;
    v_idade := (v_item->>'idade')::int;
    IF v_idade > 120 THEN RAISE EXCEPTION 'Idade inválida para %.', v_item->>'nome'; END IF;
    IF length(btrim(coalesce(v_item->>'parentesco',''))) = 0 THEN RAISE EXCEPTION 'Informe o parentesco de %.', v_item->>'nome'; END IF;
    -- Faixas do formulário original: acima de 18 / 13 a 17 / até 12.
    IF v_idade >= 18 THEN v_ad := v_ad + 1; ELSIF v_idade >= 13 THEN v_ad13 := v_ad13 + 1; ELSE v_cr := v_cr + 1; END IF;
  END LOOP;
  SELECT EXISTS (SELECT 1 FROM evento_respostas r WHERE r.evento_id = v_ev.id AND r.usuario_id = p_usuario_id) INTO v_existia;
  RETURN QUERY
  INSERT INTO evento_respostas AS r (evento_id, usuario_id, vai_participar, email, ja_participou, acompanhantes,
                                qtd_adultos, qtd_13_17, qtd_ate_12, tempo_empresa)
  VALUES (v_ev.id, p_usuario_id, p_vai, v_email, p_ja_participou, v_ac, v_ad, v_ad13, v_cr, tempo_de_empresa(v_u.admissao, v_hoje))
  ON CONFLICT (evento_id, usuario_id) DO UPDATE SET
    vai_participar = EXCLUDED.vai_participar, email = EXCLUDED.email, ja_participou = EXCLUDED.ja_participou,
    acompanhantes = EXCLUDED.acompanhantes, qtd_adultos = EXCLUDED.qtd_adultos, qtd_13_17 = EXCLUDED.qtd_13_17,
    qtd_ate_12 = EXCLUDED.qtd_ate_12, tempo_empresa = EXCLUDED.tempo_empresa, atualizado_em = now()
  RETURNING r.respondido_em, r.atualizado_em, NOT v_existia;
END;
$$;

-- No link público: só diz SE a pessoa já respondeu e quando (sem revelar o conteúdo).
CREATE OR REPLACE FUNCTION public.status_resposta_evento(p_slug text, p_usuario_id integer)
RETURNS TABLE(respondido_em timestamptz, atualizado_em timestamptz)
LANGUAGE sql SECURITY DEFINER SET search_path TO 'public' STABLE
AS $$
  SELECT r.respondido_em, r.atualizado_em FROM evento_respostas r JOIN eventos e ON e.id = r.evento_id
  WHERE e.slug = p_slug AND r.usuario_id = p_usuario_id;
$$;

-- Aba do RH: respostas completas. Confere se quem pede é RH/dev ativo.
-- Limite conhecido: sem Supabase Auth o id de quem pede vem do navegador (mesma limitação do resto do portal).
CREATE OR REPLACE FUNCTION public.respostas_evento(p_evento_id bigint, p_pedido_por integer)
RETURNS SETOF public.evento_respostas
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM usuarios WHERE id = p_pedido_por AND role IN ('rh','dev') AND coalesce(status,'ativo')='ativo') THEN
    RAISE EXCEPTION 'Acesso permitido apenas para RH.';
  END IF;
  RETURN QUERY SELECT * FROM evento_respostas WHERE evento_id = p_evento_id ORDER BY respondido_em;
END;
$$;

-- RH cria/edita evento (nome, prazo) e abre/encerra inscrições.
CREATE OR REPLACE FUNCTION public.salvar_evento(p_pedido_por integer, p_id bigint, p_nome text, p_prazo date, p_aberto boolean)
RETURNS public.eventos
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE v eventos; v_slug text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM usuarios WHERE id = p_pedido_por AND role IN ('rh','dev') AND coalesce(status,'ativo')='ativo') THEN
    RAISE EXCEPTION 'Acesso permitido apenas para RH.';
  END IF;
  IF length(btrim(coalesce(p_nome,''))) < 3 THEN RAISE EXCEPTION 'Informe o nome do evento.'; END IF;
  IF p_id IS NULL THEN
    -- slug a partir do nome + ano, sem acentos; garante unicidade com sufixo
    v_slug := trim(both '-' from regexp_replace(lower(translate(p_nome,'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ','aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC')),'[^a-z0-9]+','-','g'));
    IF EXISTS (SELECT 1 FROM eventos WHERE slug = v_slug) THEN v_slug := v_slug || '-' || substr(md5(random()::text),1,4); END IF;
    INSERT INTO eventos (nome, slug, aberto, prazo, criado_por) VALUES (btrim(p_nome), v_slug, coalesce(p_aberto,true), p_prazo, p_pedido_por) RETURNING * INTO v;
  ELSE
    UPDATE eventos SET nome = btrim(p_nome), prazo = p_prazo, aberto = coalesce(p_aberto, aberto) WHERE id = p_id RETURNING * INTO v;
    IF NOT FOUND THEN RAISE EXCEPTION 'Evento não encontrado.'; END IF;
  END IF;
  RETURN v;
END;
$$;

