-- Verificado como anon (com rollback): RH cria (token de 64 caracteres, 15 dias); não-RH recusado ao criar/listar;
-- link inválido recusado; envio sem ciência LGPD, faltando campo, com CPF inválido ou 5 dependentes recusado; envio
-- correto grava; RH confere e o candidato não altera mais; link vencido recusado; renovar invalida o link antigo;
-- anon sem SELECT direto na tabela.
--
-- Pré-admissão com ficha de registro preenchida pelo candidato (pedido do Asael, 15/10/2026).
-- Fluxo: candidato aprovado no Recrutamento → RH clica "Iniciar admissão" → portal gera link individual (token
-- aleatório, 15 dias) → candidato preenche a ficha (mesmos campos da DADOS_CADASTRAIS da BRIT) → RH confere, completa o
-- vínculo e gera a ficha da BRIT (Excel) e o kit de admissão.
-- Dados pessoais (inclusive de dependentes e bancários): tabela SEM acesso direto do navegador; só pelas funções abaixo.
CREATE TABLE public.admissoes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidato_id     integer REFERENCES public.candidatos(id) ON DELETE SET NULL,
  nome             text NOT NULL,
  email            text,
  telefone         text,
  cargo            text,
  token            text NOT NULL UNIQUE,                       -- vai no link (?admissao=<token>)
  token_expira_em  timestamptz NOT NULL,
  status           text NOT NULL DEFAULT 'aguardando' CHECK (status IN ('aguardando','preenchida','conferida','cancelada')),
  dados_candidato  jsonb NOT NULL DEFAULT '{}'::jsonb,         -- ficha preenchida pelo candidato
  dados_empresa    jsonb NOT NULL DEFAULT '{}'::jsonb,         -- vínculo preenchido pelo RH
  consentimento_em timestamptz,                                -- ciência LGPD no envio da ficha
  criado_por       integer REFERENCES public.usuarios(id),
  criado_em        timestamptz NOT NULL DEFAULT now(),
  preenchida_em    timestamptz,
  conferida_em     timestamptz,
  atualizado_em    timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.admissoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admissoes FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.eh_rh(p_id integer) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT EXISTS (SELECT 1 FROM usuarios WHERE id = p_id AND role IN ('rh','dev') AND coalesce(status,'ativo')='ativo');
$$;
REVOKE ALL ON FUNCTION public.eh_rh(integer) FROM PUBLIC;

-- RH: cria a pré-admissão e o link.
CREATE OR REPLACE FUNCTION public.admissao_criar(p_pedido_por integer, p_candidato_id integer, p_nome text, p_email text, p_telefone text, p_cargo text)
RETURNS TABLE(id bigint, token text, token_expira_em timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_nome text := btrim(coalesce(p_nome,''));
BEGIN
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Acesso permitido apenas para RH.'; END IF;
  IF length(v_nome) < 3 THEN RAISE EXCEPTION 'Informe o nome do candidato.'; END IF;
  IF p_candidato_id IS NOT NULL AND EXISTS (SELECT 1 FROM admissoes a WHERE a.candidato_id = p_candidato_id AND a.status <> 'cancelada') THEN
    RAISE EXCEPTION 'Este candidato já tem uma admissão em andamento.';
  END IF;
  RETURN QUERY INSERT INTO admissoes AS a (candidato_id, nome, email, telefone, cargo, token, token_expira_em, criado_por)
    VALUES (p_candidato_id, v_nome, nullif(btrim(coalesce(p_email,'')),''), nullif(btrim(coalesce(p_telefone,'')),''), nullif(btrim(coalesce(p_cargo,'')),''),
            replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''), now() + interval '15 days', p_pedido_por)
    RETURNING a.id, a.token, a.token_expira_em;
END; $$;

-- RH: lista as pré-admissões (com a ficha, para conferir).
CREATE OR REPLACE FUNCTION public.admissao_listar(p_pedido_por integer)
RETURNS SETOF public.admissoes LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Acesso permitido apenas para RH.'; END IF;
  RETURN QUERY SELECT * FROM admissoes ORDER BY criado_em DESC;
END; $$;

-- RH: grava os dados do vínculo e/ou muda o status (conferida, cancelada); renovar = novo link por mais 15 dias.
CREATE OR REPLACE FUNCTION public.admissao_atualizar(p_pedido_por integer, p_id bigint, p_dados_empresa jsonb, p_status text, p_renovar_link boolean DEFAULT false)
RETURNS public.admissoes LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v admissoes;
BEGIN
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Acesso permitido apenas para RH.'; END IF;
  IF p_status IS NOT NULL AND p_status NOT IN ('aguardando','preenchida','conferida','cancelada') THEN RAISE EXCEPTION 'Status inválido.'; END IF;
  UPDATE admissoes a SET
    dados_empresa = coalesce(p_dados_empresa, a.dados_empresa),
    status = coalesce(p_status, a.status),
    conferida_em = CASE WHEN p_status = 'conferida' THEN now() ELSE a.conferida_em END,
    token = CASE WHEN p_renovar_link THEN replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '') ELSE a.token END,
    token_expira_em = CASE WHEN p_renovar_link THEN now() + interval '15 days' ELSE a.token_expira_em END,
    atualizado_em = now()
  WHERE a.id = p_id RETURNING a.* INTO v;
  IF NOT FOUND THEN RAISE EXCEPTION 'Admissão não encontrada.'; END IF;
  RETURN v;
END; $$;

-- Link público: o candidato vê só a PRÓPRIA ficha (o token é o segredo).
CREATE OR REPLACE FUNCTION public.admissao_ficha(p_token text)
RETURNS TABLE(nome text, email text, telefone text, cargo text, status text, token_expira_em timestamptz, dados_candidato jsonb)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  IF p_token IS NULL OR length(p_token) < 32 THEN RAISE EXCEPTION 'Link inválido.'; END IF;
  RETURN QUERY SELECT a.nome, a.email, a.telefone, a.cargo, a.status, a.token_expira_em, a.dados_candidato FROM admissoes a WHERE a.token = p_token;
END; $$;

-- Link público: envio da ficha. Valida no servidor. Pode reenviar enquanto o RH não conferir.
CREATE OR REPLACE FUNCTION public.admissao_enviar(p_token text, p_dados jsonb, p_consentimento boolean)
RETURNS timestamptz LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v admissoes; d jsonb := coalesce(p_dados,'{}'::jsonb); k text; dep jsonb; v_nasc date;
BEGIN
  SELECT * INTO v FROM admissoes WHERE token = p_token;
  IF NOT FOUND THEN RAISE EXCEPTION 'Link inválido.'; END IF;
  IF v.status IN ('conferida','cancelada') THEN RAISE EXCEPTION 'Esta ficha já foi conferida pelo RH. Para alterar, fale com o RH.'; END IF;
  IF now() > v.token_expira_em THEN RAISE EXCEPTION 'Este link expirou. Peça um novo link ao RH.'; END IF;
  IF p_consentimento IS NOT TRUE THEN RAISE EXCEPTION 'É preciso confirmar a ciência sobre o uso dos dados.'; END IF;
  IF jsonb_typeof(d) <> 'object' THEN RAISE EXCEPTION 'Dados inválidos.'; END IF;
  FOREACH k IN ARRAY ARRAY['nome','sexo','raca','mae','nascimento','escolaridade','estado_civil','naturalidade','telefone',
                           'logradouro','numero','bairro','cep','cidade','rg','cpf'] LOOP
    IF length(btrim(coalesce(d->>k,''))) = 0 THEN RAISE EXCEPTION 'Campo obrigatório não preenchido: %.', k; END IF;
  END LOOP;
  IF NOT cpf_valido(d->>'cpf') THEN RAISE EXCEPTION 'CPF inválido (confira os números).'; END IF;
  IF (d->>'sexo') NOT IN ('M','F') THEN RAISE EXCEPTION 'Sexo inválido.'; END IF;
  BEGIN v_nasc := (d->>'nascimento')::date; EXCEPTION WHEN others THEN RAISE EXCEPTION 'Data de nascimento inválida.'; END;
  IF v_nasc > (now() AT TIME ZONE 'America/Sao_Paulo')::date - interval '14 years' OR v_nasc < date '1930-01-01' THEN RAISE EXCEPTION 'Data de nascimento fora do esperado.'; END IF;
  IF regexp_replace(d->>'cep','\D','','g') !~ '^\d{8}$' THEN RAISE EXCEPTION 'CEP inválido (8 números).'; END IF;
  IF coalesce(d->>'email','') <> '' AND (d->>'email') !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN RAISE EXCEPTION 'E-mail inválido.'; END IF;
  IF jsonb_typeof(coalesce(d->'dependentes','[]'::jsonb)) <> 'array' OR jsonb_array_length(coalesce(d->'dependentes','[]'::jsonb)) > 4 THEN
    RAISE EXCEPTION 'Informe no máximo 4 dependentes (a ficha da BRIT tem 4 linhas).'; END IF;
  FOR dep IN SELECT * FROM jsonb_array_elements(coalesce(d->'dependentes','[]'::jsonb)) LOOP
    IF length(btrim(coalesce(dep->>'nome',''))) < 3 OR length(btrim(coalesce(dep->>'vinculo',''))) = 0 THEN
      RAISE EXCEPTION 'Informe nome e vínculo de cada dependente.'; END IF;
  END LOOP;
  IF octet_length(d::text) > 20000 THEN RAISE EXCEPTION 'Dados grandes demais.'; END IF;
  UPDATE admissoes SET dados_candidato = d, status = 'preenchida', preenchida_em = now(), consentimento_em = now(), atualizado_em = now()
  WHERE id = v.id;
  RETURN now();
END; $$;

REVOKE ALL ON FUNCTION public.admissao_criar(integer,integer,text,text,text,text), public.admissao_listar(integer),
  public.admissao_atualizar(integer,bigint,jsonb,text,boolean), public.admissao_ficha(text), public.admissao_enviar(text,jsonb,boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admissao_criar(integer,integer,text,text,text,text), public.admissao_listar(integer),
  public.admissao_atualizar(integer,bigint,jsonb,text,boolean), public.admissao_ficha(text), public.admissao_enviar(text,jsonb,boolean) TO anon, authenticated;
