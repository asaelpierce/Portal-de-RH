-- Aplicada em 29/10/2026 (versão 20261029140929). Verificado (rollback, sessões reais): RH corrige (cadastro muda e
-- fica o registro); centro de custo inventado recusado; colaborador não consegue usar.
--
-- Ajuste manual de centro de custo pela conferência dos rateios. Pedido do Asael: ao conferir um rateio, o RH vê quem
-- está em cada centro de custo e, se alguém estiver errado, corrige ali mesmo; o portal registra e refaz o rateio. A
-- correção vai para o cadastro (vale para todos os relatórios e próximos meses) e para o centro de custo fixo dos
-- vínculos do odonto, quando houver (desligados). Fica registrada em centro_custo_ajustes. Só RH.
CREATE TABLE public.centro_custo_ajustes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  de text, para text NOT NULL, origem text,
  feito_por integer REFERENCES public.usuarios(id), feito_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.centro_custo_ajustes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.centro_custo_ajustes FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.centro_custo_ajustar(p_pedido_por integer, p_usuario_id integer, p_centro_custo text, p_origem text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE u usuarios; v_cc text := nullif(btrim(coalesce(p_centro_custo,'')),'');
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH corrige centro de custo.'; END IF;
  SELECT * INTO u FROM usuarios WHERE id = p_usuario_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Colaborador não encontrado.'; END IF;
  IF v_cc IS NULL OR NOT EXISTS (SELECT 1 FROM usuarios WHERE centro_custo = v_cc) THEN RAISE EXCEPTION 'Escolha um centro de custo da folha.'; END IF;
  IF u.centro_custo IS NOT DISTINCT FROM v_cc AND NOT EXISTS (SELECT 1 FROM odonto_titulares WHERE usuario_id = u.id AND centro_custo_fixo IS DISTINCT FROM v_cc AND centro_custo_fixo IS NOT NULL) THEN
    RETURN jsonb_build_object('mudou', false);
  END IF;
  INSERT INTO centro_custo_ajustes (usuario_id, de, para, origem, feito_por) VALUES (u.id, u.centro_custo, v_cc, left(p_origem, 80), p_pedido_por);
  UPDATE usuarios SET centro_custo = v_cc WHERE id = u.id;
  UPDATE odonto_titulares SET centro_custo_fixo = v_cc, atualizado_por = p_pedido_por, atualizado_em = now()
   WHERE usuario_id = u.id AND centro_custo_fixo IS NOT NULL;
  RETURN jsonb_build_object('mudou', true, 'de', u.centro_custo, 'para', v_cc);
END; $$;
REVOKE ALL ON FUNCTION public.centro_custo_ajustar(integer,integer,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.centro_custo_ajustar(integer,integer,text,text) TO authenticated;
