CREATE OR REPLACE FUNCTION public.status_resposta_evento_convidado(p_slug text, p_convidado_id bigint)
RETURNS TABLE(respondido_em timestamptz, atualizado_em timestamptz) LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT r.respondido_em, r.atualizado_em FROM evento_respostas r JOIN eventos e ON e.id = r.evento_id
  WHERE e.slug = p_slug AND r.convidado_id = p_convidado_id;
$$;
