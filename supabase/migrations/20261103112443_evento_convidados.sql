CREATE TABLE public.evento_convidados (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id bigint NOT NULL REFERENCES public.eventos(id) ON DELETE CASCADE,
  nome text NOT NULL CHECK (length(btrim(nome)) >= 3),
  observacao text, criado_por integer REFERENCES public.usuarios(id), criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (evento_id, nome)
);
ALTER TABLE public.evento_convidados ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.evento_convidados FROM anon, authenticated;

ALTER TABLE public.evento_respostas ALTER COLUMN usuario_id DROP NOT NULL,
  ADD COLUMN convidado_id bigint REFERENCES public.evento_convidados(id) ON DELETE CASCADE,
  ADD CONSTRAINT evento_respostas_quem CHECK ((usuario_id IS NULL) <> (convidado_id IS NULL)),
  ADD CONSTRAINT evento_respostas_evento_convidado_key UNIQUE (evento_id, convidado_id);

CREATE OR REPLACE FUNCTION public.evento_convidados_listar(p_slug text)
RETURNS TABLE(id bigint, nome text) LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'public' AS $$
  SELECT c.id, c.nome FROM evento_convidados c JOIN eventos e ON e.id = c.evento_id WHERE e.slug = p_slug ORDER BY c.nome;
$$;
GRANT EXECUTE ON FUNCTION public.evento_convidados_listar(text) TO anon, authenticated;

