  executado_em timestamptz NOT NULL DEFAULT now(),
  modo         text NOT NULL,            -- teste | envio
  total        integer NOT NULL,
  enviados     integer NOT NULL,
  falhas       integer NOT NULL,
  detalhes     jsonb
);
ALTER TABLE public.relatorio_ferias_envios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.relatorio_ferias_envios FROM anon, authenticated;  -- só a Edge Function grava/lê

