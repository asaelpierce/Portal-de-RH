-- A função confere o segredo e devolve os destinatários. Só a service_role (Edge Function) executa.
CREATE OR REPLACE FUNCTION public.relatorio_ferias_config(p_segredo text)
RETURNS TABLE(rh_ids integer[])
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'private', 'public'
AS $$
BEGIN
  IF p_segredo IS NULL OR p_segredo IS DISTINCT FROM (SELECT valor FROM private.config WHERE chave = 'relatorio_ferias_segredo') THEN
    RAISE EXCEPTION 'não autorizado';
  END IF;
  RETURN QUERY SELECT string_to_array(valor, ',')::integer[] FROM private.config WHERE chave = 'relatorio_ferias_rh_ids';
END;
$$;
REVOKE ALL ON FUNCTION public.relatorio_ferias_config(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.relatorio_ferias_config(text) TO service_role;

-- Registro de cada execução (auditoria: quando rodou, quantos saíram, quais falharam).
CREATE TABLE public.relatorio_ferias_envios (
