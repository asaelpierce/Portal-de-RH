-- 12 de 12 funcionários encontrados (8 pela matrícula; Renata, Daniela, Luciene e Wagner pelo nome — matrícula da Araujo
-- diferente da folha, apontada na conferência); total do convênio R$ 1.258,81 = "Soma Total" do PDF; compras acima do
-- convênio apontadas (Renata, Daniela, Wilker); rateio pelo centro de custo da folha.
--
-- Convênio Drogaria Araujo — rateio mensal por centro de custo (21/10/2026).
-- O RH anexa o "Relatório Total Compras agrupado por Funcionário e Período" (PDF). O rateio usa o TOTAL CONVÊNIO de
-- cada funcionário (o que a empresa paga à Araujo), com o centro de custo da folha da BRIT. Cada linha é ligada ao
-- cadastro pela matrícula (cadastro da folha); se a matrícula da Araujo não bater, pelo nome (todas as palavras do nome
-- da Araujo contidas no nome do cadastro, um único resultado) — e o vínculo fica guardado pela matrícula da Araujo.

CREATE TABLE public.araujo_vinculos (
  matricula_araujo text PRIMARY KEY,
  nome_araujo text,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  origem text NOT NULL DEFAULT 'automatico' CHECK (origem IN ('automatico','rh')),
  atualizado_por integer REFERENCES public.usuarios(id),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.araujo_relatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia text NOT NULL UNIQUE CHECK (competencia ~ '^\d{4}-\d{2}$'),
  periodo text, arquivo_nome text,
  total numeric(12,2) NOT NULL, pessoas integer NOT NULL,
  linhas jsonb NOT NULL, rateio jsonb NOT NULL, conferencia jsonb NOT NULL,
  gerado_por integer REFERENCES public.usuarios(id), gerado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.araujo_vinculos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.araujo_relatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.araujo_vinculos, public.araujo_relatorios FROM anon, authenticated;

-- Todas as palavras (≥ 2 letras) do nome da Araujo aparecem no nome do cadastro? (a Araujo abrevia: "DANIELA OLIVEIRA")
CREATE OR REPLACE FUNCTION public.nome_contido(p_curto text, p_completo text) RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path TO 'public' AS $$
  SELECT NOT EXISTS (SELECT 1 FROM unnest(string_to_array(sv_norm(p_curto), ' ')) w
                     WHERE length(w) >= 2 AND NOT (w = ANY (string_to_array(sv_norm(p_completo), ' '))));
$$;
REVOKE ALL ON FUNCTION public.nome_contido(text,text) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.araujo_conferir(p_pedido_por integer, p_competencia text, p_periodo text, p_arquivo text, p_linhas jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_linhas jsonb; v_rateio jsonb; v_conf jsonb; v_total numeric; v_pessoas int; t record; v_uid int; v_n int;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio do convênio Araujo.'; END IF;
  IF coalesce(p_competencia,'') !~ '^\d{4}-\d{2}$' THEN RAISE EXCEPTION 'Competência inválida (esperado AAAA-MM).'; END IF;
  IF jsonb_typeof(p_linhas) <> 'array' OR jsonb_array_length(p_linhas) = 0 THEN RAISE EXCEPTION 'Nenhum funcionário lido do relatório.'; END IF;

  -- Matrículas da Araujo que não batem com a folha e ainda não têm vínculo: tenta pelo nome (resultado único) e guarda.
  FOR t IN SELECT e->>'matricula' AS mat, e->>'nome' AS nome FROM jsonb_array_elements(p_linhas) e
           WHERE NOT EXISTS (SELECT 1 FROM usuarios u WHERE ltrim(u.cadastro,'0') = ltrim(e->>'matricula','0') AND ltrim(e->>'matricula','0') <> '')
             AND NOT EXISTS (SELECT 1 FROM araujo_vinculos v WHERE v.matricula_araujo = e->>'matricula') LOOP
    SELECT count(*), min(u.id) INTO v_n, v_uid FROM usuarios u WHERE nome_contido(t.nome, u.name) AND coalesce(u.status,'ativo') = 'ativo';
    IF v_n = 1 THEN
      INSERT INTO araujo_vinculos (matricula_araujo, nome_araujo, usuario_id, origem, atualizado_por) VALUES (t.mat, t.nome, v_uid, 'automatico', p_pedido_por);
    END IF;
  END LOOP;

  SELECT jsonb_agg(jsonb_build_object('matricula', e->>'matricula', 'nome', e->>'nome',
           'compras', (e->>'compras')::numeric, 'convenio', (e->>'convenio')::numeric, 'subsidio', (e->>'subsidio')::numeric,
           'sem_subsidio', (e->>'sem_subsidio')::numeric, 'usuario_id', u.id, 'colaborador', u.name, 'status', u.status,
           'data_desligamento', u.data_desligamento, 'cadastro', u.cadastro, 'centro_custo', u.centro_custo,
           'achado_por', CASE WHEN uc.id IS NOT NULL THEN 'matricula' WHEN v.usuario_id IS NOT NULL THEN 'vinculo' END) ORDER BY ord)
  INTO v_linhas
  FROM jsonb_array_elements(p_linhas) WITH ORDINALITY AS x(e, ord)
  LEFT JOIN LATERAL (SELECT u2.id FROM usuarios u2 WHERE ltrim(u2.cadastro,'0') = ltrim(e->>'matricula','0') AND ltrim(e->>'matricula','0') <> ''
                     ORDER BY (u2.status = 'ativo') DESC LIMIT 1) uc ON true
  LEFT JOIN araujo_vinculos v ON v.matricula_araujo = e->>'matricula' AND uc.id IS NULL
  LEFT JOIN usuarios u ON u.id = coalesce(uc.id, v.usuario_id);

  SELECT round(sum((e->>'convenio')::numeric),2), count(*) FILTER (WHERE (e->>'convenio')::numeric > 0) INTO v_total, v_pessoas FROM jsonb_array_elements(v_linhas) e;

  SELECT coalesce(jsonb_agg(jsonb_build_object('centro_custo', cc, 'pessoas', n, 'valor', v) ORDER BY cc), '[]'::jsonb) INTO v_rateio FROM (
    SELECT coalesce(e->>'centro_custo', 'SEM CENTRO DE CUSTO (verificar)') AS cc, count(*) AS n, round(sum((e->>'convenio')::numeric),2) AS v
    FROM jsonb_array_elements(v_linhas) e WHERE (e->>'convenio')::numeric > 0 GROUP BY 1) r;

  v_conf := jsonb_build_object(
    'nao_encontrados', coalesce((SELECT jsonb_agg(jsonb_build_object('matricula', e->>'matricula', 'nome', e->>'nome'))
                                 FROM jsonb_array_elements(v_linhas) e WHERE e->>'usuario_id' IS NULL), '[]'),
    'matricula_diferente', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', e->>'colaborador', 'araujo', e->>'matricula', 'folha', e->>'cadastro'))
                                 FROM jsonb_array_elements(v_linhas) e WHERE e->>'achado_por' = 'vinculo'), '[]'),
    'sem_centro_custo', coalesce((SELECT jsonb_agg(e->>'colaborador') FROM jsonb_array_elements(v_linhas) e
                                 WHERE e->>'usuario_id' IS NOT NULL AND e->>'centro_custo' IS NULL AND (e->>'convenio')::numeric > 0), '[]'),
    'desligados_com_compra', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', e->>'colaborador', 'desligamento', e->>'data_desligamento', 'convenio', (e->>'convenio')::numeric))
                                 FROM jsonb_array_elements(v_linhas) e WHERE e->>'status' = 'desligado' AND (e->>'compras')::numeric > 0), '[]'),
    'compras_acima_do_convenio', coalesce((SELECT jsonb_agg(jsonb_build_object('nome', coalesce(e->>'colaborador', e->>'nome'), 'compras', (e->>'compras')::numeric, 'convenio', (e->>'convenio')::numeric))
                                 FROM jsonb_array_elements(v_linhas) e WHERE (e->>'compras')::numeric > (e->>'convenio')::numeric), '[]'));

  INSERT INTO araujo_relatorios (competencia, periodo, arquivo_nome, total, pessoas, linhas, rateio, conferencia, gerado_por)
  VALUES (p_competencia, left(p_periodo,60), left(p_arquivo,200), v_total, v_pessoas, v_linhas, v_rateio, v_conf, p_pedido_por)
  ON CONFLICT (competencia) DO UPDATE SET periodo = EXCLUDED.periodo, arquivo_nome = EXCLUDED.arquivo_nome, total = EXCLUDED.total,
    pessoas = EXCLUDED.pessoas, linhas = EXCLUDED.linhas, rateio = EXCLUDED.rateio, conferencia = EXCLUDED.conferencia,
    gerado_por = EXCLUDED.gerado_por, gerado_em = now();

  RETURN jsonb_build_object('competencia', p_competencia, 'periodo', p_periodo, 'arquivo_nome', p_arquivo, 'total', v_total, 'pessoas', v_pessoas,
                            'linhas', v_linhas, 'rateio', v_rateio, 'conferencia', v_conf, 'gerado_em', now());
END; $$;

CREATE OR REPLACE FUNCTION public.araujo_historico(p_pedido_por integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do convênio Araujo.'; END IF;
  RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('competencia', r.competencia, 'periodo', r.periodo, 'total', r.total, 'pessoas', r.pessoas,
            'gerado_em', r.gerado_em, 'gerado_por', u.name) ORDER BY r.competencia DESC)
          FROM araujo_relatorios r LEFT JOIN usuarios u ON u.id = r.gerado_por), '[]'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.araujo_obter(p_pedido_por integer, p_competencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
DECLARE r araujo_relatorios;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do convênio Araujo.'; END IF;
  SELECT * INTO r FROM araujo_relatorios WHERE competencia = p_competencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Relatório de % não encontrado.', p_competencia; END IF;
  RETURN jsonb_build_object('competencia', r.competencia, 'periodo', r.periodo, 'arquivo_nome', r.arquivo_nome, 'total', r.total, 'pessoas', r.pessoas,
                            'linhas', r.linhas, 'rateio', r.rateio, 'conferencia', r.conferencia, 'gerado_em', r.gerado_em);
END; $$;

REVOKE ALL ON FUNCTION public.araujo_conferir(integer,text,text,text,jsonb), public.araujo_historico(integer), public.araujo_obter(integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.araujo_conferir(integer,text,text,text,jsonb), public.araujo_historico(integer), public.araujo_obter(integer,text) TO authenticated;
