-- Aplicada em 21/10/2026 (versão 20261021184640). Ajustada em 20261021184936 (ligação por nome).
-- Verificado (rollback, sessão do RH) com as 35 famílias reais dos 4 PDFs de out/2026: 32 ligadas automaticamente
-- (3 desligados identificados); as 3 restantes resolvidas pelo ajuste seguinte / vínculo do RH.
--
-- Unimed BH — rateio mensal por centro de custo e descontos em folha (21/10/2026).
-- O navegador lê os PDFs (Rel1 mensalidade e Rel7 coparticipação) e calcula rateio e descontos com as regras do RH
-- (src/unimed.js). O banco: liga cada família (14 primeiros dígitos do código Unimed) ao colaborador titular — pelo
-- vínculo guardado; senão nascimento + 1º nome, nome completo ou nome contido — e guarda o relatório do mês. Só RH.

CREATE TABLE public.unimed_familias (
  familia text PRIMARY KEY CHECK (familia ~ '^\d{14}$'),
  titular_unimed text,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  origem text NOT NULL DEFAULT 'automatico' CHECK (origem IN ('automatico','rh')),
  atualizado_por integer REFERENCES public.usuarios(id),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.unimed_relatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia text NOT NULL UNIQUE CHECK (competencia ~ '^\d{4}-\d{2}$'),
  arquivo_nome text, total numeric(12,2) NOT NULL, relatorio jsonb NOT NULL,
  gerado_por integer REFERENCES public.usuarios(id), gerado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.unimed_familias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.unimed_relatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.unimed_familias, public.unimed_relatorios FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.unimed_vincular(p_pedido_por integer, p_familias jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE t record; v_uid int; v_n int;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio da Unimed.'; END IF;
  IF jsonb_typeof(p_familias) <> 'array' THEN RAISE EXCEPTION 'Lista de famílias inválida.'; END IF;
  FOR t IN SELECT e->>'familia' AS fam, e->>'titular' AS nome, nullif(e->>'nascimento','')::date AS nasc FROM jsonb_array_elements(p_familias) e
           WHERE coalesce(e->>'familia','') ~ '^\d{14}$' AND NOT EXISTS (SELECT 1 FROM unimed_familias f WHERE f.familia = e->>'familia') LOOP
    v_uid := NULL;
    IF t.nasc IS NOT NULL THEN
      SELECT u.id INTO v_uid FROM usuarios u JOIN colaboradores_documentos d ON d.usuario_id = u.id
       WHERE d.data_nascimento = t.nasc AND split_part(sv_norm(u.name),' ',1) = split_part(sv_norm(t.nome),' ',1) ORDER BY (u.status='ativo') DESC LIMIT 1;
    END IF;
    IF v_uid IS NULL THEN SELECT u.id INTO v_uid FROM usuarios u WHERE sv_norm(u.name) = sv_norm(t.nome) ORDER BY (u.status='ativo') DESC LIMIT 1; END IF;
    IF v_uid IS NULL THEN
      SELECT count(*), min(u.id) INTO v_n, v_uid FROM usuarios u WHERE nome_contido(t.nome, u.name);
      IF v_n <> 1 THEN v_uid := NULL; END IF;
    END IF;
    IF v_uid IS NOT NULL THEN
      INSERT INTO unimed_familias (familia, titular_unimed, usuario_id, origem, atualizado_por) VALUES (t.fam, t.nome, v_uid, 'automatico', p_pedido_por);
    END IF;
  END LOOP;
  RETURN coalesce((SELECT jsonb_object_agg(f.familia, jsonb_build_object('usuario_id', u.id, 'colaborador', u.name, 'cadastro', u.cadastro,
            'centro_custo', u.centro_custo, 'status', u.status, 'data_desligamento', u.data_desligamento, 'origem', f.origem))
          FROM unimed_familias f JOIN usuarios u ON u.id = f.usuario_id
          WHERE f.familia IN (SELECT e->>'familia' FROM jsonb_array_elements(p_familias) e)), '{}'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.unimed_salvar(p_pedido_por integer, p_competencia text, p_arquivo text, p_relatorio jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio da Unimed.'; END IF;
  IF coalesce(p_competencia,'') !~ '^\d{4}-\d{2}$' THEN RAISE EXCEPTION 'Competência inválida (esperado AAAA-MM).'; END IF;
  INSERT INTO unimed_relatorios (competencia, arquivo_nome, total, relatorio, gerado_por)
  VALUES (p_competencia, left(p_arquivo,400), coalesce((p_relatorio->>'total')::numeric,0), p_relatorio, p_pedido_por)
  ON CONFLICT (competencia) DO UPDATE SET arquivo_nome = EXCLUDED.arquivo_nome, total = EXCLUDED.total, relatorio = EXCLUDED.relatorio,
    gerado_por = EXCLUDED.gerado_por, gerado_em = now();
  RETURN p_relatorio || jsonb_build_object('competencia', p_competencia, 'arquivo_nome', p_arquivo, 'gerado_em', now());
END; $$;

CREATE OR REPLACE FUNCTION public.unimed_historico(p_pedido_por integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios da Unimed.'; END IF;
  RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('competencia', r.competencia, 'total', r.total,
            'colaboradores', jsonb_array_length(coalesce(r.relatorio->'descontos','[]'::jsonb)), 'gerado_em', r.gerado_em, 'gerado_por', u.name) ORDER BY r.competencia DESC)
          FROM unimed_relatorios r LEFT JOIN usuarios u ON u.id = r.gerado_por), '[]'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.unimed_obter(p_pedido_por integer, p_competencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
DECLARE r unimed_relatorios;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios da Unimed.'; END IF;
  SELECT * INTO r FROM unimed_relatorios WHERE competencia = p_competencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Relatório de % não encontrado.', p_competencia; END IF;
  RETURN r.relatorio || jsonb_build_object('competencia', r.competencia, 'arquivo_nome', r.arquivo_nome, 'gerado_em', r.gerado_em);
END; $$;

REVOKE ALL ON FUNCTION public.unimed_vincular(integer,jsonb), public.unimed_salvar(integer,text,text,jsonb), public.unimed_historico(integer), public.unimed_obter(integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.unimed_vincular(integer,jsonb), public.unimed_salvar(integer,text,text,jsonb), public.unimed_historico(integer), public.unimed_obter(integer,text) TO authenticated;
