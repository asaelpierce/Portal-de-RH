-- Verificado (rollback, sessão do RH) com amostra da fatura real 10/2026: titular comum vinculado automaticamente pela
-- data de nascimento (inclusive com nome errado no PDF: "HYGOR GUSTAVIO"); dependentes no CC do titular (folha);
-- Geraldina → Múcio; Ademar (desligado, com devolução) em CC fixo sem alarme; João Vitor (desligado, ainda cobrado)
-- apontado; titular inventado → "sem vínculo". Vínculos iniciais (titulares não funcionários e desligados) gravados a
-- partir da planilha do RH de 11/2026 (registro em supabase/dados/20261021_odonto_vinculos_iniciais.md).
--
-- Plano odontológico (Bradesco Dental) — rateio mensal por centro de custo (21/10/2026).
-- O RH anexa a "Fatura Técnica" (PDF); o navegador lê beneficiários e lançamentos; esta função agrupa por titular
-- (certificado), aplica o centro de custo OFICIAL da folha da BRIT do colaborador responsável (dependentes seguem o
-- titular), soma por centro de custo, monta a conferência e guarda o mês. O PDF não traz CPF: o titular é achado pela
-- data de nascimento + primeiro nome (ou nome completo) e o vínculo fica guardado pelo número do certificado.

CREATE TABLE public.odonto_titulares (
  certificado text PRIMARY KEY CHECK (certificado ~ '^\d{7}$'),
  nome_titular text,
  usuario_id integer REFERENCES public.usuarios(id),          -- colaborador que responde pelo titular
  centro_custo_fixo text,                                       -- quando não há centro de custo na folha (ex.: desligado)
  origem text NOT NULL DEFAULT 'automatico' CHECK (origem IN ('automatico','rh')),
  observacao text,
  atualizado_por integer REFERENCES public.usuarios(id),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  CHECK (usuario_id IS NOT NULL OR centro_custo_fixo IS NOT NULL)
);
CREATE TABLE public.odonto_relatorios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia text NOT NULL UNIQUE CHECK (competencia ~ '^\d{4}-\d{2}$'),
  vigencia text, arquivo_nome text,
  total numeric(12,2) NOT NULL, beneficiarios integer NOT NULL, titulares integer NOT NULL,
  linhas jsonb NOT NULL, rateio jsonb NOT NULL, conferencia jsonb NOT NULL,
  gerado_por integer REFERENCES public.usuarios(id), gerado_em timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.odonto_titulares ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.odonto_relatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.odonto_titulares, public.odonto_relatorios FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.odonto_conferir(p_pedido_por integer, p_competencia text, p_vigencia text, p_arquivo text, p_beneficiarios jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE v_linhas jsonb; v_rateio jsonb; v_conf jsonb; v_total numeric; v_nben int; v_ntit int; v_padrao numeric; t record; v_uid int;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH gera o rateio do plano odontológico.'; END IF;
  IF coalesce(p_competencia,'') !~ '^\d{4}-\d{2}$' THEN RAISE EXCEPTION 'Competência inválida (esperado AAAA-MM).'; END IF;
  IF jsonb_typeof(p_beneficiarios) <> 'array' OR jsonb_array_length(p_beneficiarios) = 0 THEN RAISE EXCEPTION 'Nenhum beneficiário lido da fatura.'; END IF;

  -- Titulares ainda sem vínculo: tenta achar no cadastro (data de nascimento + 1º nome; senão nome completo) e guarda.
  FOR t IN SELECT DISTINCT ON (e->>'certificado') e->>'certificado' AS cert, e->>'nome' AS nome, nullif(e->>'nascimento','')::date AS nasc
           FROM jsonb_array_elements(p_beneficiarios) e WHERE e->>'seq' = '00'
             AND NOT EXISTS (SELECT 1 FROM odonto_titulares o WHERE o.certificado = e->>'certificado') LOOP
    SELECT u.id INTO v_uid FROM usuarios u LEFT JOIN colaboradores_documentos d ON d.usuario_id = u.id
     WHERE (d.data_nascimento = t.nasc AND split_part(sv_norm(u.name),' ',1) = split_part(sv_norm(t.nome),' ',1)) OR sv_norm(u.name) = sv_norm(t.nome)
     ORDER BY (d.data_nascimento = t.nasc) DESC NULLS LAST, (u.status = 'ativo') DESC LIMIT 1;
    IF v_uid IS NOT NULL THEN
      INSERT INTO odonto_titulares (certificado, nome_titular, usuario_id, origem, atualizado_por) VALUES (t.cert, t.nome, v_uid, 'automatico', p_pedido_por);
    END IF;
  END LOOP;

  -- Cada beneficiário + titular + colaborador responsável + centro de custo (fixo do vínculo, senão o da folha).
  SELECT jsonb_agg(jsonb_build_object('certificado', e->>'certificado', 'seq', e->>'seq', 'nome', e->>'nome', 'nascimento', e->>'nascimento',
           'parentesco', e->>'parentesco', 'lancamentos', e->'lancamentos', 'valor', (e->>'valor')::numeric,
           'titular', tt.nome, 'responsavel_id', u.id, 'responsavel', u.name, 'responsavel_status', u.status,
           'data_desligamento', u.data_desligamento, 'vinculo_origem', o.origem, 'vinculo_obs', o.observacao,
           'centro_custo', coalesce(o.centro_custo_fixo, u.centro_custo)) ORDER BY ord)
  INTO v_linhas
  FROM jsonb_array_elements(p_beneficiarios) WITH ORDINALITY AS x(e, ord)
  LEFT JOIN LATERAL (SELECT y->>'nome' AS nome FROM jsonb_array_elements(p_beneficiarios) y
                     WHERE y->>'certificado' = e->>'certificado' AND y->>'seq' = '00' LIMIT 1) tt ON true
  LEFT JOIN odonto_titulares o ON o.certificado = e->>'certificado'
  LEFT JOIN usuarios u ON u.id = o.usuario_id;

  SELECT round(sum((e->>'valor')::numeric),2), count(*), count(DISTINCT e->>'certificado') INTO v_total, v_nben, v_ntit FROM jsonb_array_elements(v_linhas) e;
  -- Mensalidade padrão = valor mais comum dos lançamentos sem movimentação (hoje 21,75).
  SELECT (l->>'valor')::numeric INTO v_padrao FROM jsonb_array_elements(v_linhas) e, jsonb_array_elements(e->'lancamentos') l
  WHERE coalesce(l->>'tipo','') = '' GROUP BY 1 ORDER BY count(*) DESC, 1 LIMIT 1;

  SELECT coalesce(jsonb_agg(jsonb_build_object('centro_custo', cc, 'titulares', nt, 'beneficiarios', nb, 'valor', v) ORDER BY cc), '[]'::jsonb)
  INTO v_rateio FROM (
    SELECT coalesce(e->>'centro_custo', 'SEM CENTRO DE CUSTO (verificar)') AS cc, count(DISTINCT e->>'certificado') AS nt, count(*) AS nb,
           round(sum((e->>'valor')::numeric),2) AS v
    FROM jsonb_array_elements(v_linhas) e GROUP BY 1 HAVING round(sum((e->>'valor')::numeric),2) <> 0 OR count(*) > 0) r;

  v_conf := jsonb_build_object(
    'mensalidade_padrao', v_padrao,
    'titulares_sem_vinculo', coalesce((SELECT jsonb_agg(DISTINCT jsonb_build_object('certificado', e->>'certificado', 'titular', e->>'titular'))
                                       FROM jsonb_array_elements(v_linhas) e WHERE e->>'responsavel_id' IS NULL AND e->>'centro_custo' IS NULL), '[]'),
    'sem_centro_custo', coalesce((SELECT jsonb_agg(DISTINCT e->>'titular') FROM jsonb_array_elements(v_linhas) e
                                  WHERE e->>'responsavel_id' IS NOT NULL AND e->>'centro_custo' IS NULL), '[]'),
    'desligados_cobrados', coalesce((SELECT jsonb_agg(DISTINCT jsonb_build_object('titular', e->>'titular', 'desligamento', e->>'data_desligamento'))
                                  FROM jsonb_array_elements(v_linhas) e WHERE e->>'responsavel_status' = 'desligado'
                                    AND EXISTS (SELECT 1 FROM jsonb_array_elements(e->'lancamentos') l WHERE coalesce(l->>'tipo','') = '' AND (l->>'valor')::numeric > 0)
                                    AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(e->'lancamentos') l WHERE l->>'tipo' = 'CM')), '[]'),
    'vinculados_a_outro', coalesce((SELECT jsonb_agg(DISTINCT jsonb_build_object('titular', e->>'titular', 'responsavel', e->>'responsavel'))
                                  FROM jsonb_array_elements(v_linhas) e WHERE e->>'seq' = '00' AND e->>'responsavel' IS NOT NULL
                                    AND split_part(sv_norm(e->>'responsavel'),' ',1) <> split_part(sv_norm(e->>'titular'),' ',1)), '[]'),
    'inclusoes', coalesce((SELECT jsonb_agg(DISTINCT e->>'nome') FROM jsonb_array_elements(v_linhas) e, jsonb_array_elements(e->'lancamentos') l WHERE l->>'tipo' IN ('IM','IR')), '[]'),
    'cancelamentos', coalesce((SELECT jsonb_agg(DISTINCT e->>'nome') FROM jsonb_array_elements(v_linhas) e, jsonb_array_elements(e->'lancamentos') l WHERE l->>'tipo' IN ('CM','CR')), '[]'),
    'valor_diferente', coalesce((SELECT jsonb_agg(DISTINCT jsonb_build_object('nome', e->>'nome', 'valor', (l->>'valor')::numeric))
                                  FROM jsonb_array_elements(v_linhas) e, jsonb_array_elements(e->'lancamentos') l
                                  WHERE coalesce(l->>'tipo','') = '' AND (l->>'valor')::numeric <> v_padrao), '[]'));

  INSERT INTO odonto_relatorios (competencia, vigencia, arquivo_nome, total, beneficiarios, titulares, linhas, rateio, conferencia, gerado_por)
  VALUES (p_competencia, left(p_vigencia,60), left(p_arquivo,200), v_total, v_nben, v_ntit, v_linhas, v_rateio, v_conf, p_pedido_por)
  ON CONFLICT (competencia) DO UPDATE SET vigencia = EXCLUDED.vigencia, arquivo_nome = EXCLUDED.arquivo_nome, total = EXCLUDED.total,
    beneficiarios = EXCLUDED.beneficiarios, titulares = EXCLUDED.titulares, linhas = EXCLUDED.linhas, rateio = EXCLUDED.rateio,
    conferencia = EXCLUDED.conferencia, gerado_por = EXCLUDED.gerado_por, gerado_em = now();

  RETURN jsonb_build_object('competencia', p_competencia, 'vigencia', p_vigencia, 'arquivo_nome', p_arquivo, 'total', v_total,
    'beneficiarios', v_nben, 'titulares', v_ntit, 'linhas', v_linhas, 'rateio', v_rateio, 'conferencia', v_conf, 'gerado_em', now());
END; $$;

-- RH vincula um titular (certificado) a um colaborador e/ou a um centro de custo fixo.
CREATE OR REPLACE FUNCTION public.odonto_vincular(p_pedido_por integer, p_certificado text, p_nome_titular text, p_usuario_id integer, p_centro_custo_fixo text, p_observacao text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE r odonto_titulares;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH vincula titulares do plano odontológico.'; END IF;
  IF coalesce(p_certificado,'') !~ '^\d{7}$' THEN RAISE EXCEPTION 'Certificado inválido.'; END IF;
  IF p_usuario_id IS NULL AND nullif(btrim(coalesce(p_centro_custo_fixo,'')),'') IS NULL THEN RAISE EXCEPTION 'Escolha o colaborador responsável ou um centro de custo.'; END IF;
  INSERT INTO odonto_titulares AS o (certificado, nome_titular, usuario_id, centro_custo_fixo, origem, observacao, atualizado_por, atualizado_em)
  VALUES (p_certificado, p_nome_titular, p_usuario_id, nullif(btrim(coalesce(p_centro_custo_fixo,'')),''), 'rh', nullif(btrim(coalesce(p_observacao,'')),''), p_pedido_por, now())
  ON CONFLICT (certificado) DO UPDATE SET nome_titular = coalesce(EXCLUDED.nome_titular, o.nome_titular), usuario_id = EXCLUDED.usuario_id,
    centro_custo_fixo = EXCLUDED.centro_custo_fixo, origem = 'rh', observacao = EXCLUDED.observacao, atualizado_por = p_pedido_por, atualizado_em = now()
  RETURNING * INTO r;
  RETURN to_jsonb(r);
END; $$;

CREATE OR REPLACE FUNCTION public.odonto_historico(p_pedido_por integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do plano odontológico.'; END IF;
  RETURN coalesce((SELECT jsonb_agg(jsonb_build_object('competencia', r.competencia, 'vigencia', r.vigencia, 'total', r.total,
            'beneficiarios', r.beneficiarios, 'titulares', r.titulares, 'gerado_em', r.gerado_em, 'gerado_por', u.name) ORDER BY r.competencia DESC)
          FROM odonto_relatorios r LEFT JOIN usuarios u ON u.id = r.gerado_por), '[]'::jsonb);
END; $$;

CREATE OR REPLACE FUNCTION public.odonto_obter(p_pedido_por integer, p_competencia text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' STABLE AS $$
DECLARE r odonto_relatorios;
BEGIN
  p_pedido_por := public.quem_pede(p_pedido_por);
  IF NOT eh_rh(p_pedido_por) THEN RAISE EXCEPTION 'Só o RH acessa os relatórios do plano odontológico.'; END IF;
  SELECT * INTO r FROM odonto_relatorios WHERE competencia = p_competencia;
  IF NOT FOUND THEN RAISE EXCEPTION 'Relatório de % não encontrado.', p_competencia; END IF;
  RETURN jsonb_build_object('competencia', r.competencia, 'vigencia', r.vigencia, 'arquivo_nome', r.arquivo_nome, 'total', r.total,
    'beneficiarios', r.beneficiarios, 'titulares', r.titulares, 'linhas', r.linhas, 'rateio', r.rateio, 'conferencia', r.conferencia, 'gerado_em', r.gerado_em);
END; $$;

REVOKE ALL ON FUNCTION public.odonto_conferir(integer,text,text,text,jsonb), public.odonto_vincular(integer,text,text,integer,text,text),
  public.odonto_historico(integer), public.odonto_obter(integer,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.odonto_conferir(integer,text,text,text,jsonb), public.odonto_vincular(integer,text,text,integer,text,text),
  public.odonto_historico(integer), public.odonto_obter(integer,text) TO authenticated;
